#!/usr/bin/env python3
"""FIKRA DESIGN SYSTEM · exact palette extraction from the original «فكرة» logo.

Usage:
    python3 brand/tools/extract_palette.py brand/source/fikra-logo.png

Reads the ORIGINAL logo file (PNG/JPG/WebP), ignores transparent and
background-white pixels, clusters the remaining pixels and, for every
cluster, picks the single most frequent *actual* pixel value — so the
resulting hex codes are exact colours present in the logo, never averages
or approximations. Writes:

    brand/palette.json                     (full report)
    app/src/theme/brand.generated.ts       (tokens consumed by the app)
    admin/src/brand.generated.ts           (tokens consumed by the admin panel)
"""
import colorsys, hashlib, json, pathlib, sys
from collections import Counter
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]


def hexc(rgb):
    return "#{:02X}{:02X}{:02X}".format(*rgb)


def lum(rgb):
    def ch(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def pixels(im):
    return list(im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata())


def extract(path: pathlib.Path):
    img = Image.open(path).convert("RGBA")
    if max(img.size) > 900:
        img.thumbnail((900, 900), Image.NEAREST)  # NEAREST keeps exact pixel values
    px = [p[:3] for p in pixels(img) if p[3] >= 230]
    bg = Counter(px).most_common(1)[0][0] if px else (255, 255, 255)
    ink_px = [p for p in px if not (min(p) > 238) and sum(abs(a - b) for a, b in zip(p, bg)) > 30]
    if not ink_px:
        raise SystemExit("No logo colours found (image is empty or only background).")

    # Median-cut quantisation on the logo pixels only.
    q_src = Image.new("RGB", (len(ink_px), 1))
    q_src.putdata(ink_px)
    q = q_src.quantize(colors=8, method=Image.Quantize.MEDIANCUT)
    labels = pixels(q)
    clusters = {}
    for lab, p in zip(labels, ink_px):
        clusters.setdefault(lab, Counter())[p] += 1

    total = len(ink_px)
    found = []
    for lab, counter in clusters.items():
        exact, _ = counter.most_common(1)[0]
        share = sum(counter.values()) / total
        h, l, s = colorsys.rgb_to_hls(*(c / 255 for c in exact))
        chroma = max(exact) - min(exact)
        found.append(dict(hex=hexc(exact), rgb=list(exact), share=round(share, 4), hue=round(h * 360, 1),
                          lightness=round(l, 3), chroma=chroma))
    found.sort(key=lambda c: -c["share"])

    chromatic = [c for c in found if c["chroma"] >= 40 and c["share"] >= 0.005]
    def hue_in(c, lo, hi):
        h = c["hue"]
        return lo <= h <= hi if lo <= hi else (h >= lo or h <= hi)
    def pick(lo, hi):
        return next((c for c in chromatic if hue_in(c, lo, hi)), None)
    turquoise = pick(150, 200)
    yellow = pick(38, 65)
    red = pick(340, 15)
    neutrals = [c for c in found if c["chroma"] < 40]
    dark = min(neutrals, key=lambda c: lum(c["rgb"])) if neutrals else None
    primary_bright = (turquoise or (chromatic[0] if chromatic else found[0]))["hex"]
    return dict(
        source=str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path),
        sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
        background=hexc(bg),
        colors=found,
        roles=dict(
            primaryBright=primary_bright,
            primary=darken_for_white_text(primary_bright),
            featured=(yellow or {"hex": "#FFC629"})["hex"],
            alert=(red or {"hex": "#D32F2F"})["hex"],
            ink=(dark["hex"] if dark and lum(dark["rgb"]) < 0.08 else "#111111"),
        ),
    )


def darken_for_white_text(hex_):
    """Same hue, darkened only as much as needed for 4.5:1 with white text."""
    r, g, b = (int(hex_[i:i + 2], 16) for i in (1, 3, 5))
    for k in range(0, 60):
        f = 1 - k / 100
        rgb = (round(r * f), round(g * f), round(b * f))
        if (1.05) / (lum(rgb) + 0.05) >= 4.5:
            return hexc(rgb)
    return hex_


def write_outputs(report):
    roles = report["roles"]
    (ROOT / "brand" / "palette.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf8")
    ts = (
        "// GENERATED by brand/tools/extract_palette.py from the original logo — do not edit by hand.\n"
        f"// source: {report['source']}  sha256: {report['sha256'][:16]}…\n"
        "export const brand = {\n"
        f"  source: 'logo' as 'logo' | 'interim',\n"
        f"  primary: '{roles['primary']}',\n"
        f"  primaryBright: '{roles['primaryBright']}',\n"
        f"  featured: '{roles['featured']}',\n"
        f"  alert: '{roles['alert']}',\n"
        f"  ink: '{roles['ink']}',\n"
        f"  logoColors: {json.dumps([c['hex'] for c in report['colors']])},\n"
        "} as const;\n"
    )
    for target in (ROOT / "app" / "src" / "theme" / "brand.generated.ts", ROOT / "admin" / "src" / "brand.generated.ts"):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(ts, encoding="utf8")


if __name__ == "__main__":
    src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "brand" / "source" / "fikra-logo.png").resolve()
    if not src.exists():
        raise SystemExit(f"Logo not found: {src}\nPlace the ORIGINAL «فكرة» logo at brand/source/fikra-logo.png")
    rep = extract(src)
    write_outputs(rep)
    print(json.dumps(rep["roles"], indent=2))
    for c in rep["colors"]:
        print(f"  {c['hex']}  share={c['share']:.3f}  hue={c['hue']}  chroma={c['chroma']}")
