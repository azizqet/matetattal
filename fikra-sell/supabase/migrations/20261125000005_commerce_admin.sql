-- FIKRA SELL · 0005 · Notifications, commerce (ready, payments disabled), content, support, audit

create table public.notifications (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  type text not null check (type in ('message', 'ad_approved', 'ad_rejected', 'ad_expired', 'ad_expiring',
    'saved_search', 'offer', 'general', 'support')),
  title_ar text not null,
  title_en text not null,
  body_ar text not null default '',
  body_en text not null default '',
  data jsonb not null default '{}'::jsonb,
  read_at timestamptz,
  pushed_at timestamptz,
  created_at timestamptz not null default now()
);
create index notifications_user_idx on public.notifications (user_id, created_at desc);
create index notifications_unread_idx on public.notifications (user_id) where read_at is null;
create index notifications_push_idx on public.notifications (created_at) where pushed_at is null;

-- Now that notifications exist, attach the message trigger (defined in 0004).
create trigger messages_after_insert after insert on public.messages
  for each row execute function private.messages_after_insert();

