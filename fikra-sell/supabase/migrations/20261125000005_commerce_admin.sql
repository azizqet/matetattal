create table public.ticket_messages (
  id bigint generated always as identity primary key,
  ticket_id bigint not null references public.support_tickets(id) on delete cascade,
  sender_id uuid references public.profiles(id) on delete set null,
  is_staff boolean not null default false,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);
create index ticket_messages_ticket_idx on public.ticket_messages (ticket_id, created_at);

create or replace function private.tickets_before_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not private.is_privileged() then
    new.user_id := auth.uid(); new.status := 'open'; new.assigned_to := null;
    perform private.enforce_rate_limit('ticket:' || auth.uid(), 5, 86400, 'too_many_tickets');
  end if;
  return new;
end $$;
create trigger tickets_before_insert before insert on public.support_tickets
  for each row execute function private.tickets_before_insert();

create or replace function private.ticket_messages_before_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare t record;
begin
  select * into t from public.support_tickets where id = new.ticket_id;
  if not private.is_privileged() then
    new.sender_id := auth.uid();
    new.is_staff := public.has_perm('support') and t.user_id <> auth.uid();
    if t.user_id <> auth.uid() and not new.is_staff then
      raise exception using errcode = 'P0403', message = 'forbidden';
    end if;
    perform private.enforce_rate_limit('ticket_msg:' || auth.uid(), 20, 3600, 'too_many_messages');
  end if;
  return new;
end $$;
create trigger ticket_messages_before_insert before insert on public.ticket_messages
  for each row execute function private.ticket_messages_before_insert();

create or replace function private.ticket_messages_after_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare t record;
begin
  update public.support_tickets set updated_at = now(),
    status = case when new.is_staff then 'pending'::public.ticket_status else 'open'::public.ticket_status end
  where id = new.ticket_id returning * into t;
  if new.is_staff then
    insert into public.notifications (user_id, type, title_ar, title_en, body_ar, body_en, data)
    values (t.user_id, 'support', 'رد من الدعم الفني', 'Support replied', left(new.body, 120), left(new.body, 120),
            jsonb_build_object('ticket_id', t.id));
  end if;
  return null;
end $$;
create trigger ticket_messages_after_insert after insert on public.ticket_messages
  for each row execute function private.ticket_messages_after_insert();

