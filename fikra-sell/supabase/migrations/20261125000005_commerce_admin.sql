create or replace function private.audit(p_action text, p_target_type text, p_target_id text, p_details jsonb default '{}'::jsonb)
returns void language sql security definer set search_path = '' as $$
  insert into public.audit_log (actor_id, action, target_type, target_id, details)
  values (auth.uid(), p_action, p_target_type, p_target_id, coalesce(p_details, '{}'::jsonb))
$$;

-- Generic audit trigger for admin-managed configuration tables.
create or replace function private.audit_config_change()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  -- Ignore system counter updates (ads_count, impressions, clicks, used_count).
  if tg_op = 'UPDATE' and (to_jsonb(new) - '{ads_count,impressions,clicks,used_count,updated_at}'::text[])
                        = (to_jsonb(old) - '{ads_count,impressions,clicks,used_count,updated_at}'::text[]) then
    return null;
  end if;
  if auth.uid() is not null then
    perform private.audit(lower(tg_op), tg_table_name,
      coalesce((to_jsonb(new) ->> (tg_argv[0])), (to_jsonb(old) ->> (tg_argv[0]))),
      case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end);
  end if;
  return null;
end $$;

